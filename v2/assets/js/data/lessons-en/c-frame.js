LCEN("c-frame-1", {
  why:"Briefs usually describe a **symptom**: bad reviews, falling revenue, staff leaving. A team that solves the symptom proposes things that sound reasonable but never touch the cause — and judges see it immediately.",
  outcome:"work from symptom down to root cause with a chain of \"why\", each level backed by a number.",
  scenario:{text:"A food delivery app has seen 1-star reviews double in a quarter. Management wants to run a customer care campaign.",
            ask:"Would a customer care campaign solve the problem?"},
  fw:{title:"Ask \"why\" until you reach something the business controls",
      rows:[["Symptom","What you can see: 1-star reviews are up"],
            ["Direct cause","Read the reviews: 70% complain about late delivery at peak hours"],
            ["Deeper cause","Not enough drivers at peak hours"],
            ["Root cause","Bonuses are paid per order, so drivers have no reason to ride the crowded peak"],
            ["Stop when","You reach a policy, process or decision the business can change"]],
      warn:"Every \"why\" level needs a number behind it. Without numbers, a causal chain is just plausible speculation."},
  ex:{label:"Food delivery app · lunchtime peak",
      rows:[["Orders per hour","12,000"],["Drivers online","3,000"],["Capacity per driver","3 orders/hour"],
            ["1-star reviews mentioning lateness","70%"]],
      read:"3,000 drivers × 3 orders covers only 9,000 orders an hour. The shortage is delivery capacity, not customer care."},
  mini:{q:"What is the root cause?",
        opts:[["A","The bonus scheme gives drivers no reason to ride at peak","Correct. This is something the business can change, and it explains the driver shortage at exactly the busiest hour."],
              ["B","Customers are getting harder to please","No data, and the business cannot control it."],
              ["C","Late deliveries","That is the direct cause — still a symptom of something deeper."],
              ["D","The support team replies slowly","It does not explain why orders arrive late."]],
        correct:"A", kind:"framework"},
  calc:{q:"How many extra drivers does the peak hour need to deliver every order?", unit:"drivers", answer:1000, tol:0.5,
        solution:"Current capacity 3,000 × 3 = 9,000 orders/hour. Shortfall 12,000 − 9,000 = 3,000 orders ÷ 3 = **1,000 drivers** — a 33% increase, at the peak hour specifically.",
        hint:"Work out the undelivered orders per hour, then divide by one driver's capacity."},
  slide:{headline:"1-star reviews rose because the peak is 1,000 drivers short — the root cause is the per-order bonus",
         left:"A four-step ladder: 1-star → late delivery → driver shortage → bonus scheme, each step with a number", right:"3 points: 3,000 orders/hour short · +33% drivers needed · pay bonuses by time slot",
         rule:"Draw the causal chain as a ladder, with a confirming number on every rung."},
  mistakes:[["Fixing the symptom","Customer care does not make orders arrive sooner."],
            ["Stopping at the direct cause","\"Late delivery\" is still not something you can fix."],
            ["Going too deep","\"The labour market\" is outside the company's reach."],
            ["No number per level","A causal chain without numbers is easy for judges to reject."]],
  checklist:["Tell a symptom from a root cause","Work through at least three levels of why","Confirm each level with data",
             "Stop at something the business can change","Quantify the gap"],
  arena:"cl-01"
});

LCEN("c-frame-2", {
  why:"The problem statement is **the one sentence the team and the judges both look at** for the whole competition. Write it vaguely and everyone reads it differently, and recommendations drift off in unrelated directions.",
  outcome:"write a one-sentence problem statement with a metric, a starting point, a target, a deadline and a constraint — then quantify what the target is worth.",
  scenario:{text:"The brief: a gym chain with 20,000 members, average package 500,000đ a month, churn 6% a month. Management wants to \"improve the member experience\" and will not cut prices.",
            ask:"Is \"improve the member experience\" a good problem statement?"},
  fw:{title:"Problem statement = Metric · From · To · Deadline · Constraint",
      rows:[["Metric","One measurable number: churn, margin, market share"],
            ["From → To","Where you are now and where you want to be"],
            ["Deadline","By when"],
            ["Constraint","What must not be done, or the limit on resources"],
            ["The test","After the deadline, can you answer \"did we hit it or not\"?"]],
      warn:"Do not put a solution inside the problem statement. \"Cut churn with a new app\" already locks the team into one answer."},
  ex:{label:"Gym chain",
      rows:[["Members","20,000"],["Average package price","500,000đ/month"],["Current churn","6%/month"],
            ["Target suggested by management","around 4%/month"],["Constraint","no price cuts"]],
      read:"Every ingredient for one measurable sentence is here: churn as the metric, 6% → 4%, 12 months, no price cuts."},
  mini:{q:"Which is the best problem statement?",
        opts:[["A","\"Cut member churn from 6% to 4% a month over the next 12 months, without cutting package prices\"","Correct. A metric, two levels, a deadline and a constraint — after 12 months you know immediately whether it was hit."],
              ["B","\"Improve the member experience\"","Not measurable, no deadline."],
              ["C","\"Launch a booking app to retain members\"","A solution smuggled into the problem."],
              ["D","\"Become the best-loved gym chain\"","A slogan, not a problem."]],
        correct:"A", kind:"presentation"},
  calc:{q:"If churn falls from 6% to 4%, how many extra members does the chain keep each month?", unit:"members/month", answer:400, tol:0.5,
        solution:"20,000 × (6% − 4%) = **400 members a month**. At 500,000đ a package that is 200 million of retained revenue a month — a number worth putting straight under the problem statement.",
        hint:"Multiply the member base by the reduction in churn."},
  slide:{headline:"Cut churn from 6% to 4% a month over 12 months without price cuts — 400 members retained every month",
         left:"The problem statement large in the centre, the five ingredients underlined beneath it", right:"3 points: 400 members/month · 200 million of revenue a month · the no-discount constraint",
         rule:"Put the cash value of the target right next to the problem statement — judges then see why it matters."},
  mistakes:[["An unmeasurable target","\"Improve\" and \"enhance\" have no finish line."],
            ["Putting a solution in the sentence","It locks the team in before any analysis."],
            ["Forgetting the constraint","A price-cut recommendation breaks management's requirement on the spot."],
            ["Writing several sentences","A problem statement is one sentence."]],
  checklist:["Choose one measurable metric","Write the current level and the target","Set a deadline",
             "State the constraint","Quantify what the target is worth"],
  arena:"cl-01"
});

LCEN("c-frame-3", {
  why:"Teams want to recommend everything so they look comprehensive. Judges reward **teams that choose**: they say what is out of scope and why, then prove the in-scope options are enough to hit the target.",
  outcome:"draw the scope from the brief's constraints, and check whether the in-scope options close the gap.",
  scenario:{text:"The brief: a fashion chain with 1,500 billion of revenue (stores 1,400 billion, online 100 billion) must grow revenue 20% in 2 years. The company will **raise no new capital** and will not enter foreign markets.",
            ask:"Should \"acquire a competing chain\" appear in the deck?"},
  fw:{title:"Scope = In · Out · Reason · Sufficiency check",
      rows:[["In scope","Options that respect every constraint in the brief"],
            ["Out of scope","Options that break a constraint or exceed the horizon — name them so judges see you considered them"],
            ["Reason","Each exclusion needs one sentence tied to a constraint"],
            ["Sufficiency check","Add up the in-scope impact — does it close the gap to the target?"]],
      warn:"If the in-scope options are not enough, say the gap out loud rather than quietly pulling an out-of-scope option back in."},
  ex:{label:"Fashion chain · existing 2-year plan",
      rows:[["Existing store revenue","1,400 billion","+8%"],["Online revenue","100 → 220 billion"],
            ["Target","+20% total revenue"],["Constraints","no new capital · no foreign markets"]],
      read:"Both routes are in scope. The question is whether together they add up to 20%."},
  mini:{q:"Given the constraints, which option must go out of scope?",
        opts:[["A","Acquire a competing chain","Correct. A deal needs significant capital — it breaks the no-new-capital constraint."],
              ["B","Raise revenue per existing store","It respects every constraint."],
              ["C","Expand the online channel","No major capital, domestic."],
              ["D","Sell more accessories in existing stores","In scope."]],
        correct:"A", kind:"logic"},
  calc:{q:"After the existing plan (stores +8%, online up to 220 billion), how many billion short of the +20% target is the company?", unit:"billion VND", answer:68, tol:0.5,
        solution:"Target +20% × 1,500 = 300 billion. Stores +8% × 1,400 = 112 billion; online +120 billion. Total 232 billion → still **68 billion** short. The team needs more in-scope levers, not an acquisition.",
        hint:"Compute the required increase, then subtract the store and online increases."},
  slide:{headline:"The existing plan delivers 232 billion, leaving 68 billion — closed with in-scope levers, no acquisition needed",
         left:"A two-column In · Out of scope table, each out-of-scope line with its reason", right:"3 points: +112 stores · +120 online · 68 billion gap",
         rule:"State the gap openly on the scope slide — it is the bridge into the recommendations."},
  mistakes:[["Recommending something that breaks a constraint","You lose feasibility points instantly."],
            ["Saying nothing about excluded options","Judges assume the team never thought of them."],
            ["Skipping the sufficiency check","A sensible scope that still misses the target."],
            ["Applying growth to the total instead of the part","Stores grow 8% on 1,400 billion, not on 1,500."]],
  checklist:["List the brief's constraints","Sort options into in and out of scope","Give a reason for each exclusion",
             "Add up the in-scope impact","State the remaining gap"],
  arena:"cl-11"
});
