  scenario:{text:"A garment workshop has four steps: cutting, sewing, pressing, packing. The supervisor thinks packing is slow, because the packers often stand idle and then rush at the end of the shift. Input to the workshop is 540 units an hour.",
            ask:"Where is the bottleneck?"},
  fw:{title:"Three bottleneck signals: utilisation · queue · the next step waiting",
      rows:[["Utilisation","Busy time ÷ available time — a bottleneck runs near 100%"],
            ["Queue (WIP)","Work in progress piling up in front of a step — it grows continuously before the bottleneck"],
            ["Next step waiting","The step right after the bottleneck sits idle and then rushes"],
            ["Build-up rate","Input per hour − the bottleneck's throughput per hour"]],
      warn:"Idle workers downstream are a symptom of an upstream bottleneck, not evidence that they are slow."},
  ex:{label:"Garment workshop · per hour",
      rows:[["Cutting","utilisation 70%"],["Sewing","utilisation 98%","1,200 units waiting","down"],
            ["Pressing","utilisation 60%"],["Packing","utilisation 75%","often waiting"],["Sewing throughput","500 units/hour"]],
      read:"Sewing is almost always busy with a mountain of work in front of it. Pressing and packing are idle because work arrives slowly from sewing."},
