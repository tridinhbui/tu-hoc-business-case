LCEN("c-deck-1", {
  why:"Judges watch 20–30 presentations in a day. A deck in a **familiar structure** lets them follow the argument first time — a creatively structured deck usually loses them by slide three.",
  outcome:"build the standard 10-slide competition deck and allocate speaking time by section.",
  scenario:{text:"The team has 15 minutes and a maximum of 10 main slides. The current draft opens with three market-introduction slides and reaches the recommendation on slide 8.",
            ask:"At what minute will the judges learn the team's answer?"},
  fw:{title:"A 10-slide deck: Answer first · Proof · How · Risks · The ask",
      rows:[["Slide 1","Executive summary: the answer and three reasons"],
            ["Slide 2","The problem and the target, in numbers"],
            ["Slides 3–5","Three analysis pillars, one per slide"],
            ["Slides 6–7","Recommendations and financial impact"],
            ["Slides 8–9","Implementation roadmap, and risks with mitigations"],
            ["Slide 10","A specific ask of management · appendix for Q&A"]],
      warn:"Generic market information does not need its own slide. Put the numbers you need inside the analysis pillars."},
  ex:{label:"15-minute presentation · allocation by section",
      rows:[["Opening and executive summary","10%"],["Three analysis pillars","45%"],["Recommendations and financials","25%"],
            ["Roadmap and risks","20%"]],
      read:"Almost half the time goes to analysis, but the answer has already been said in the first 90 seconds."},
  mini:{q:"What should slide 1 be?",
        opts:[["A","Executive summary: the answer and the three main reasons","Correct. Judges know immediately what you propose and hear everything after it as evidence."],
              ["B","Introducing the team members","It burns the most valuable time in the presentation."],
              ["C","A market overview","Context the judges already read in the brief."],
              ["D","A table of contents","It carries no message."]],
        correct:"A", kind:"presentation"},
  calc:{q:"With 15 minutes, how many minutes do the three analysis pillars (45%) get?", unit:"minutes", answer:6.75, tol:0.01,
        solution:"15 × 45% = **6.75 minutes** — about 2 minutes 15 seconds per pillar. Opening 1.5 minutes, recommendations and financials 3.75 minutes, roadmap and risks 3 minutes.",
        hint:"Multiply the total time by the analysis share."},
  slide:{headline:"A 10-slide deck: the answer in the first minute, three pillars of proof in under 7 minutes",
         left:"A strip of 10 slide boxes, colour-coded into five sections", right:"3 points: slide 1 is the answer · about 2m15s per pillar · appendix for Q&A",
         rule:"If judges only ever saw slide 1, they should still know what you recommend."},
  mistakes:[["Saving the answer for the end","Judges listen for 10 minutes without knowing what it is for."],
            ["A market introduction slide","It repeats the brief."],
            ["No risk slide","Judges will ask — and the team looks as if it never considered them."],
            ["Cramming every analysis into the main deck","Secondary analysis belongs in the appendix."]],
  checklist:["Open with an executive summary","One slide per analysis pillar","Include a financial slide and a risk slide",
             "Allocate speaking time by section","Prepare an appendix for Q&A"],
  arena:"cl-07"
});

LCEN("c-deck-2", {
  why:"Judges scan the titles before reading the body. An **action title** — a conclusion with a number — lets them understand the whole deck by reading titles in sequence.",
  outcome:"write action titles carrying a number, and compute compound growth to put in one.",
  scenario:{text:"A team slide is titled \"Online channel revenue 2023–2025\". The chart shows online going from 120 billion to 300 billion in two years, while stores grow 8% a year.",
            ask:"Rewrite that title."},
  fw:{title:"Action title = Conclusion · Number · Implication (two lines maximum)",
      rows:[["Conclusion","What the reader should believe after this slide"],
            ["Number","The single most important figure that proves it"],
            ["Implication","If it fits, what it means for the recommendation"],
            ["Chain test","Read the titles in sequence — they should tell one continuous story"]],
      warn:"A label title (\"Online revenue\") makes the reader draw their own conclusion — and they may draw the wrong one."},
  ex:{label:"Revenue by channel",
      rows:[["Online 2023","120 billion"],["Online 2025","300 billion"],["Stores","+8%/year"],["Years","2"]],
      read:"Online grew 2.5× in two years. To compare it with stores at 8% a year, convert it to an annual rate."},
  mini:{q:"Which title is best?",
        opts:[["A","\"Online is growing 58% a year, seven times faster than stores\"","Correct. One conclusion, one comparable number, understood on the first read."],
              ["B","\"Online channel revenue 2023–2025\"","A label title — no conclusion."],
              ["C","\"Online grew 150%\"","The right number, but not comparable with the stores' annual rate."],
              ["D","\"Online is the future of retail\"","A slogan, with no number from the data."]],
        correct:"A", kind:"presentation"},
  calc:{q:"What is the online channel's compound annual growth rate (CAGR)?", unit:"%", answer:58.1, tol:0.05,
        solution:"(300 ÷ 120)^(1/2) − 1 = √2.5 − 1 = **58.1% a year** — roughly seven times the stores' 8%.",
        hint:"Take the square root of 300/120 (two years) and subtract 1."},
  slide:{headline:"Online is growing 58% a year, seven times faster than stores",
         left:"Two growth lines by channel, each labelled with its CAGR at the end", right:"3 points: 120 → 300 billion · stores +8%/year · shift budget towards online",
         rule:"Write the title before building the chart. The chart proves the title, not the other way round."},
  mistakes:[["Label titles","The reader has to guess the message."],
            ["Total growth instead of annual","150% over two years is not comparable with 8% a year."],
            ["Titles that run too long","More than two lines is a paragraph."],
            ["A title number that differs from the chart","Judges lose trust instantly."]],
  checklist:["Write the title as a conclusion","Put the key number in the title","Convert growth to an annual rate when comparing",
             "Keep titles to two lines","Read the titles in sequence to check the flow"],
  arena:"cl-07"
});

LCEN("c-deck-3", {
  why:"With the same numbers, the wrong chart makes the message disappear. Each message type — comparison, trend, composition, decomposition, correlation — has **one chart that fits best**.",
  outcome:"pick the chart that matches the message and build a waterfall that adds up.",
  scenario:{text:"The team's message: \"EBITDA goes from 84 billion to 180 billion through three levers: selective price rises, cost savings and closing loss-making stores.\" The draft uses a pie chart.",
            ask:"What should replace the pie?"},
  fw:{title:"Message type → chart type",
      rows:[["Comparing values","Horizontal bars, sorted largest to smallest"],
            ["Trend over time","Lines"],
            ["Composition","100% stacked bars, or a pie when there are only 2–3 parts"],
            ["Decomposing a change","Waterfall: start → each lever → end"],
            ["Correlation","Scatter plot"]],
      warn:"A waterfall must add up: start + every bar = end. One wrong bar and the judges spot it immediately."},
  ex:{label:"EBITDA waterfall · billion VND",
      rows:[["Current EBITDA","84"],["Selective price rises","+40"],["Cost savings","?"],
            ["Closing loss-making stores","−10","lost revenue exceeds the cost saved"],["2028 EBITDA","180"]],
      read:"One bar is blank. It must take the value that makes the waterfall land on 180."},
  mini:{q:"Which chart fits \"EBITDA goes from 84 to 180 billion through three levers\"?",
        opts:[["A","A waterfall","Correct. It shows the starting point, each lever's plus or minus, and the end point in one picture."],
              ["B","A pie","A pie shows the composition of one total, not a move from start to end, and it has no negative slices."],
              ["C","A line chart","For trends over time."],
              ["D","A scatter plot","For correlation between two variables."]],
        correct:"A", kind:"presentation"},
  calc:{q:"What must the \"cost savings\" bar be, in billion, for the waterfall to reach 180?", unit:"billion VND", answer:66, tol:0.1,
        solution:"180 − 84 − 40 + 10 = **66 billion**. Check: 84 + 40 + 66 − 10 = 180.",
        hint:"End point less the start and the known bars; remember the store-closure bar is negative."},
  slide:{headline:"Cost savings are the largest lever: 66 of the 96 billion of EBITDA growth",
         left:"Waterfall 84 → +40 → +66 → −10 → 180, with the 66 bar highlighted", right:"3 points: selective price rises 40 · cost savings 66 · store closures −10 in the short term",
         rule:"Highlight the most important bar in a waterfall — the reader's eye then lands in the right place."},
  mistakes:[["Using a pie for a change","No start, no end, no negative values."],
            ["A waterfall that does not add up","Credibility is gone the moment a judge adds it up."],
            ["Unsorted comparison bars","Sort largest to smallest."],
            ["Several chart types on one slide","One chart, one message per slide."]],
  checklist:["Identify the message type","Pick the chart that fits it","Build a waterfall with negative bars",
             "Check that the waterfall adds up","Highlight the most important element"],
  arena:"cl-07"
});
