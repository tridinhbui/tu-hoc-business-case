LCEN("c-insight-1", {
  why:"Competition decks are full of lines like \"Q3 revenue fell 10%\". That is an observation. Judges pay for an **insight**: something non-obvious, with a number, that explains why and leads to an action.",
  outcome:"tell observation, finding and insight apart, and compute a group's contribution to a total change.",
  scenario:{text:"The brief: a bubble tea chain's Q3 revenue is down 50 billion. The data shows the 18–24 age group accounts for 42 billion of it. In the same quarter a rival started offering free delivery on small orders.",
            ask:"Write one insight sentence from this data."},
  fw:{title:"Observation → Finding → Insight",
      rows:[["Observation","What the numbers show: revenue down 50 billion"],
            ["Finding","Cut the data and see where it concentrates: the fall is mostly in the 18–24 group"],
            ["Insight","Why, and what it means: this group is the most delivery-fee sensitive and is moving to the rival offering free delivery"],
            ["The test","A good insight makes the listener want to do something differently"]],
      warn:"An insight needs a number and a cause. Missing either one and you are still at a finding."},
  ex:{label:"Bubble tea chain · Q3",
      rows:[["Revenue decline","50 billion"],["Decline in 18–24","42 billion"],["Decline in all other groups","8 billion"],
            ["Competitor","free delivery on small orders from the start of the quarter"]],
      read:"Nearly the entire decline sits in one age group, and it coincides with a competitor's change."},
  mini:{q:"Which sentence is an insight?",
        opts:[["A","\"18–24s account for 84% of the decline because the rival made small-order delivery free — this group is the most fee-sensitive\"","Correct. A number, a cause, and an immediate direction for action on small-order delivery fees."],
              ["B","\"Q3 revenue fell 50 billion\"","An observation."],
              ["C","\"The decline is mostly among 18–24s\"","A finding — no why yet."],
              ["D","\"The bubble tea market is saturating\"","No number, not tied to the brief's data."]],
        correct:"A", kind:"logic"},
  calc:{q:"What share of the revenue decline comes from the 18–24 group?", unit:"%", answer:84, tol:0.1,
        solution:"42 ÷ 50 = **84%** of the decline from one age group — concentrated enough to aim the recommendation straight at it.",
        hint:"Divide the group's decline by the total decline."},
  slide:{headline:"84% of the lost revenue comes from 18–24s, who are moving to the rival's free small-order delivery",
         left:"Waterfall of the 50 billion decline by age group, with 18–24 highlighted", right:"3 points: 42 of 50 billion · coincides with the rival's free delivery · trial zero delivery fee on small orders for this group",
         rule:"The headline of an insight slide is the insight itself — not a topic label."},
  mistakes:[["Stopping at the observation","Describing numbers is not analysis."],
            ["An insight without a number","\"Young customers are leaving\" is not enough."],
            ["Inferring cause from timing alone","Say openly that it is a strong hypothesis still to be tested."],
            ["An insight with no action","If nobody would act differently, it is not an insight."]],
  checklist:["Tell observation, finding and insight apart","Cut the data to find where it concentrates","Compute a group's contribution",
             "Attach a cause with evidence","Write the insight as a slide headline"],
  arena:"cl-03"
});

LCEN("c-insight-2", {
  why:"A total often looks stable because opposing movements cancel out. Three cuts — **by segment, by cohort, and per unit** — are the fastest way to expose what the total hides.",
  outcome:"use the three cuts, cohort especially, to find the problem behind a stable average.",
  scenario:{text:"The brief: an e-wallet reports a steady 5% monthly user drop-off. Management believes everything is normal. Mid-year, the company changed its signup bonus policy.",
            ask:"Is a steady 5% really fine?"},
  fw:{title:"Three cuts: Segment · Cohort · Unit",
      rows:[["Segment","Split by customer group, product, region, channel"],
            ["Cohort","Split by when the customer started — it exposes a policy change immediately"],
            ["Unit","Reduce to one customer, one order, one store for a fair comparison"],
            ["When to cut","The total is stable while something big changed inside the period"]],
      warn:"An average of two groups moving in opposite directions can sit perfectly still. A stable total does not mean stable parts."},
  ex:{label:"E-wallet · active users",
      rows:[["Cohort before the policy change","30,000 users","3%/month drop-off"],
            ["Cohort after the policy change","20,000 users","8%/month drop-off"],
            ["Blended rate","5%/month","looks stable"]],
      read:"Users acquired under the new bonus leave nearly three times as fast. A healthy old cohort is masking an unhealthy new one."},
  mini:{q:"The blended 5% looks stable. Which cut exposes the problem?",
        opts:[["A","Cut by signup period (cohort)","Correct. The policy changed mid-year — before and after cohorts show the effect immediately."],
              ["B","Take a full-year average","It blurs the problem further."],
              ["C","Cut by gender","Unrelated to the policy change."],
              ["D","No cut needed, the rate is stable","It ignores the signal that something big changed in the period."]],
        correct:"A", kind:"exhibit"},
  calc:{q:"If the later cohort dropped off at the earlier cohort's 3%, how many fewer users would leave each month?", unit:"users/month", answer:1000, tol:0.5,
        solution:"20,000 × (8% − 3%) = **1,000 users a month**. The blended rate (900 + 1,600) ÷ 50,000 = 5% hides exactly that loss.",
        hint:"Multiply the later cohort's size by the gap in drop-off rates."},
  slide:{headline:"The 5% drop-off hides the problem: users on the new bonus leave at 8%, costing 1,000 extra users a month",
         left:"Two drop-off lines by cohort, diverging at the policy change", right:"3 points: old cohort 3% · new cohort 8% · revisit the signup bonus terms",
         rule:"A cohort chart is the strongest evidence when you want to show the effect of a policy change."},
  mistakes:[["Trusting the total","A stable total can be two parts moving in opposite directions."],
            ["Cutting at random","Choose the cut that matches what changed in the period."],
            ["Comparing cohorts of different ages","Compare at the same number of months since signup."],
            ["Not reducing to a unit","Comparing totals across groups of different size misleads."]],
  checklist:["Name the three cuts","Spot the signal that a cut is needed","Split the data by cohort",
             "Compute the bad cohort's impact","Write a headline naming what the total hid"],
  arena:"cl-03"
});

LCEN("c-insight-3", {
  why:"A wrong insight on a slide is worse than none: one question from the judges and the argument collapses. **Four checks** before it goes on a slide keep the team from being caught in Q&A.",
  outcome:"validate an insight by comparing like with like, ruling out alternative explanations, and recomputing the real gap.",
  scenario:{text:"The team finds that stores with an automatic espresso machine have 25% higher revenue than stores without. They want to recommend rolling the machines out chain-wide. But 8 of the 10 machine stores sit inside shopping malls.",
            ask:"Does \"the machine lifts revenue 25%\" hold up?"},
  fw:{title:"Four checks before an insight goes on a slide",
      rows:[["Enough sample","How many stores, how many months? 10 stores is a small sample"],
            ["Compare like with like","Same location type, same size, same period"],
            ["Rule out other explanations","Is there something that comes with the machine and also lifts revenue?"],
            ["Recompute","Redo the number from the raw data rather than copying a note"]],
      warn:"Two things moving together does not mean one causes the other. A mall location comes with the machine and also lifts revenue."},
  ex:{label:"Coffee chain · average revenue per store per month",
      rows:[["With machine · all (10 stores)","1.5 billion","8 in malls"],["Without machine · all (40 stores)","1.2 billion"],
            ["With machine · inside malls","1.55 billion"],["Without machine · inside malls","1.48 billion"]],
      read:"Comparing within malls, the gap narrows sharply. Most of the 25% is location."},
  mini:{q:"Which check comes first?",
        opts:[["A","Compare within the same location type (mall against mall) to remove the location effect","Correct. Location is the most obvious alternative explanation — rule it out before believing the machine is the cause."],
              ["B","Make a prettier chart","It does not make the insight more true."],
              ["C","Install machines chain-wide as a trial","Expensive before validation."],
              ["D","Ask the machine supplier","A source with an interest in the conclusion."]],
        correct:"A", kind:"logic"},
  calc:{q:"Within malls, how much higher is revenue in stores with a machine?", unit:"%", answer:4.7, tol:0.05,
        solution:"(1.55 − 1.48) ÷ 1.48 = **4.7%** — not 25%. Across all stores: (1.5 − 1.2) ÷ 1.2 = 25%, but most of that is the location effect.",
        hint:"Use only the two in-mall figures."},
  slide:{headline:"Comparing like with like, the machine is associated with about 5% higher revenue — not 25%",
         left:"Two pairs of columns: all stores (25%) and within malls (4.7%)", right:"3 points: 8 of 10 machines are in malls · a 10-store sample is small · run a controlled pilot before a chain-wide rollout",
         rule:"When validation shrinks an insight, say so on the slide — judges value honesty with the data."},
  mistakes:[["Reading correlation as causation","Location causes both."],
            ["Comparing groups with different characteristics","Mall stores and street stores are not directly comparable."],
            ["Too small a sample","10 stores easily produce a random result."],
            ["Hiding the validation result","If judges find it themselves, the whole deck loses credibility."]],
  checklist:["Check the sample size","Compare within the same group","Find and rule out alternative explanations",
             "Recompute the real gap","Present the validated result honestly"],
  arena:"cl-03"
});
