LCEN("i-chart-2", {
  why:"Every chart type has its own familiar way of **misleading**. Interviewers sometimes plant one deliberately to see whether you read the numbers or just the picture.",
  outcome:"recognise the traps in common chart types and recompute the real number from the data labels.",
  scenario:{text:"The interviewer shows a two-year revenue bar chart: this year's bar is twice as tall as last year's. The labels read 950 billion and 1,000 billion.",
            ask:"Did revenue double?"},
  fw:{title:"Seven common chart types and their traps",
      rows:[["Bars","An axis that does not start at zero makes a small gap look enormous"],
            ["Pie","Too many slices, or slices of similar size — the eye cannot compare angles"],
            ["Dual-axis lines","Two independent scales; slopes and crossings can be manufactured"],
            ["Stacked bars","Only the bottom layer shares a baseline — middle layers cannot be compared by eye"],
            ["Log scale","Each gridline is a multiple, not an addition"],
            ["Cumulative","Always rises, even while each period is falling"],
            ["% versus absolute","A 100% rise on a tiny base is still a tiny number"]],
      warn:"Always trust the data labels over the height of the drawing."},
  ex:{label:"Revenue bar chart · y-axis starts at 900 billion",
      rows:[["Last year's revenue","950 billion","bar height 50 units"],["This year's revenue","1,000 billion","bar height 100 units"],
            ["Ratio of bar heights","2×"]],
      read:"Bar height measures the amount above 900 billion, not revenue. The 2× ratio is an artefact of the truncated axis."},
  mini:{q:"Which chart type makes middle layers hardest to compare?",
        opts:[["A","Stacked bars — only the bottom layer shares a baseline","Correct. Upper layers start at different heights, so the eye cannot compare their lengths."],
              ["B","Simple bars starting at zero","The easiest type to compare."],
              ["C","A data table","No visual comparison problem at all."],
              ["D","A single-axis line chart","Excellent for trends."]],
        correct:"A", kind:"exhibit"},
  calc:{q:"By what percentage did revenue actually rise?", unit:"%", answer:5.3, tol:0.05,
        solution:"(1,000 − 950) ÷ 950 = **5.3%** — not the 100% the bar heights suggest. Starting the axis at 900 billion exaggerated the gap about nineteen-fold.",
        hint:"Use the data labels, not the bar heights."},
  slide:{headline:"Revenue rose 5.3%, not double — the original chart truncated the axis at 900 billion",
         left:"Redraw the two bars with the axis starting at zero", right:"3 points: +50 billion · 5.3% · always read labels before shapes",
         rule:"When you catch a misleading chart, redraw it correctly rather than just saying it is wrong."},
  mistakes:[["Trusting bar heights","A truncated axis makes the picture lie."],
            ["Comparing pie angles","Use percentage labels, or switch to bars."],
            ["Comparing middle stacked layers","Split them into side-by-side bars if they must be compared."],
            ["Reading a log scale as linear","One gridline is ten times."]],
  checklist:["Check whether the axis starts at zero","Name the pie and stacked-bar traps","Recognise log scales and cumulative charts",
             "Recompute the real number from the labels","Propose a correct redraw"],
  arena:"cl-03"
});

LCEN("i-chart-3", {
  why:"Anyone can describe a chart. Interviewers pay for the **so-what**: observation → meaning → action. Without the last step, chart reading is just reading numbers aloud.",
  outcome:"turn a chart observation into an insight with a number and an implication for action.",
  scenario:{text:"The interviewer shows three-month churn for a food ordering app, split by acquisition source: customers who arrived on a promo code, and customers who found the app themselves.",
            ask:"What do you say after reading it?"},
  fw:{title:"Observation → Meaning → Action",
      rows:[["Observation","The most striking number or trend, stated numerically"],
            ["Meaning","Why it matters for the case question"],
            ["Action","What should be done differently, or what data to check next"],
            ["Length","Three sentences, no more"]],
      warn:"Do not stop at an observation with an adjective (\"churn is very high\"). The third sentence is what earns points."},
  ex:{label:"Food ordering app · new customers this quarter",
      rows:[["From promo codes","60% of new customers","45% churn after 3 months"],
            ["Found the app themselves","40% of new customers","15% churn after 3 months"],
            ["Company target","blended churn below 25%"]],
      read:"Promo customers leave three times as fast. And they are the majority of new customers — pulling the blended rate up."},
  mini:{q:"What is the best so-what?",
        opts:[["A","\"Promotions are buying customers who do not stay — shift budget towards organic, or move the code to the second order\"","Correct. It carries meaning and a specific action drawn from the 45% against 15% gap."],
              ["B","\"Promo customers churn 45% after three months\"","Only an observation."],
              ["C","\"Churn is very high\"","No number, no implication."],
              ["D","\"We need more data before concluding\"","The data already supports a conditional conclusion."]],
        correct:"A", kind:"logic"},
  calc:{q:"What is the blended three-month churn across all new customers?", unit:"%", answer:33, tol:0.1,
        solution:"60% × 45% + 40% × 15% = 27% + 6% = **33%**. If promo customers fell to 30% of intake, the blended rate would be 24%.",
        hint:"A weighted average by each source's share."},
  slide:{speak:true,
         headline:"\"Promo-code customers churn 45% within three months, three times the organic rate — and they are 60% of new customers.\"",
         left:"\"So about a third of the customers we pay to acquire disappear within a quarter; the blended rate is 33%.\"",
         right:"\"I'd move part of the discount budget into organic channels, or apply the code only to the second order to filter for customers who stay.\"",
         rule:"Three sentences: one number, one meaning, one action."},
  mistakes:[["Stopping at the observation","Without the third sentence there is no insight."],
            ["Using adjectives instead of numbers","\"Very high\" cannot be compared."],
            ["An action not grounded in the data","The recommendation must come from the gap on the chart."],
            ["Talking too long","Beyond three sentences you are re-narrating the chart."]],
  checklist:["State the observation numerically","Explain what it means for the case question","Propose an action tied to the data",
             "Compute a weighted average when needed","Keep it to three sentences"],
  arena:"cl-02"
});
