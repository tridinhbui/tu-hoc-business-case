  fw:{title:"The biggest leak = the step whose fix to benchmark adds the most orders",
      rows:[["Current funnel","Multiply the rates to get today's orders"],
            ["Benchmark gap","How many points below benchmark each step sits"],
            ["Simulate the fix","Replace one step with its benchmark, hold the others, recompute orders"],
            ["Priority","The step that adds the most orders and is easiest to fix"]],
      warn:"A step already above benchmark (add-to-cart at 12% against 10%) is not the problem, even if its rate looks lowest."},
  ex:{label:"Fashion marketplace · per month",
      rows:[["Visits","100,000"],["Add to cart","12%","benchmark 10%"],["Reach checkout page","50%","benchmark 70%","down"],
            ["Payment succeeds","60%","benchmark 85%","down"],["Current orders","3,600"]],
      read:"Both final steps are below benchmark. Only simulating each one shows which is worth more."},
