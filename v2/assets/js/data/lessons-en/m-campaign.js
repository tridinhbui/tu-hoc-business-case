  fw:{title:"Revenue goal → Orders → Visits → Clicks → Impressions",
      rows:[["Orders","Revenue goal ÷ average order value"],
            ["Visits","Orders ÷ conversion rate"],
            ["Clicks","Visits ÷ landing rate (usually close to visits)"],
            ["Impressions","Clicks ÷ click-through rate"],
            ["The check","Every level has a number; you can see which level falls short during the campaign"]],
      warn:"An awareness goal with no link to revenue cannot be checked against success or failure."},
  ex:{label:"Online cosmetics · holiday season",
      rows:[["Incremental revenue goal","30 billion"],["Average order value","300,000đ"],["Conversion rate","2%"],
            ["Click-through rate","1.5%"]],
      read:"Each funnel level depends on the one below. Working back from 30 billion gives the visits you need."},
  mini:{q:"What is the best way to set campaign targets?",
        opts:[["A","Work backwards from the revenue goal into orders, visits and impressions","Correct. Every level has a number to track, and you see immediately whether the campaign is big enough."],
              ["B","\"Raise brand awareness\"","Not measurable and not linked to revenue."],
              ["C","Maximise reach","No way to know how much is enough."],
              ["D","Last year's target plus 20%","Not tied to the revenue you need this year."]],
        correct:"A", kind:"framework"},
  calc:{q:"How many million visits does the campaign need for 30 billion of extra revenue?", unit:"million visits", answer:5, tol:0.01,
        solution:"30 billion ÷ 300,000đ = 100,000 orders ÷ 2% = **5 million visits**. At a 1.5% click-through rate that means about 333 million impressions — 20 million reach falls far short.",
        hint:"Work out the orders first, then divide by the conversion rate."},
  slide:{headline:"30 billion of holiday revenue needs 5 million visits — the agency's 20 million reach target is short by multiples",
         left:"A reverse funnel: 30 billion → 100,000 orders → 5 million visits → about 333 million impressions", right:"3 points: 100,000 orders · 5 million visits · track conversion weekly",
         rule:"Read the reverse funnel top down starting with revenue — judges see immediately that the target is tied to money."},
  mistakes:[["Targets not tied to revenue","You cannot tell whether the campaign worked."],
            ["Confusing reach with visits","Seeing an ad is not visiting the site."],
            ["Over-optimistic conversion rates","The required volumes come out too low."],
            ["Not tracking each level","You cannot see which level is short."]],
  checklist:["Compute orders from the revenue goal","Compute the visits needed","Compute the impressions needed",
             "Compare with the proposed target","Set a tracking metric for each level"],
