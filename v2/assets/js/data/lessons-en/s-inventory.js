LCEN("s-inventory-1", {
  why:"Inventory is **cash sitting on a shelf**. In a case, raising inventory turns is often the fastest way to free cash without cutting revenue — and judges want to see the cash figure.",
  outcome:"compute inventory turns, days of inventory, and the cash freed by raising turns.",
  scenario:{text:"An electronics chain has 1,200 billion of annual cost of goods sold and 300 billion of average inventory. The best competitor turns inventory 6 times a year. The company's cost of capital is 12%.",
            ask:"What does the company gain by matching the competitor's turns?"},
  fw:{title:"Inventory turns = cost of goods sold ÷ average inventory",
      rows:[["Turns","How many times inventory is sold and replaced each year"],
            ["Days of inventory","365 ÷ turns"],
            ["Target inventory","Cost of goods sold ÷ target turns"],
            ["Cash freed","Current inventory − target inventory"],
            ["Annual saving","Cash freed × cost of capital"]],
      warn:"Use cost of goods sold, not revenue — inventory is carried at cost."},
  ex:{label:"Electronics chain",
      rows:[["Cost of goods sold","1,200 billion/year"],["Average inventory","300 billion"],["Current turns","4×/year","about 91 days"],
            ["Best competitor's turns","6×/year"],["Cost of capital","12%/year"]],
      read:"Stock sits for about three months. Reaching 6 turns means cutting that to about two."},
  mini:{q:"What is the lowest-risk way to raise turns?",
        opts:[["A","Cut inventory of slow-moving lines in the tail of the range first","Correct. Slow movers tie up cash and produce little revenue — cutting there barely affects customers."],
              ["B","Cut inventory evenly across every line","It creates stockouts on the bestsellers."],
              ["C","Cut inventory of the bestselling lines","It loses the most revenue."],
              ["D","Discount everything to clear it fast","It sacrifices margin on lines that were selling well."]],
        correct:"A", kind:"logic"},
  calc:{q:"At 6 turns a year, how much cash does the company free, in billion?", unit:"billion VND", answer:100, tol:0.5,
        solution:"Target inventory 1,200 ÷ 6 = 200 billion. Cash freed 300 − 200 = **100 billion**, saving 12 billion of capital cost a year. Days of inventory fall from about 91 to about 61.",
        hint:"Target inventory is cost of goods sold divided by target turns."},
  slide:{headline:"Matching the competitor's inventory turns frees 100 billion of cash and saves 12 billion a year",
         left:"Two inventory columns: 300 billion today and 200 billion target", right:"3 points: 91 → 61 days · 100 billion of cash · start with the slow movers",
         rule:"Speak in cash freed, not just in turns — a board grasps money faster than a ratio."},
  mistakes:[["Computing turns from revenue","It makes turns look better than they are."],
            ["Reporting only the turns figure","It does not express the money."],
            ["Cutting inventory evenly","It causes stockouts on fast movers."],
            ["Forgetting the cost of capital","It leaves out the annual saving."]],
  checklist:["Compute inventory turns","Compute days of inventory","Compute target inventory",
             "Compute the cash freed","Compute the annual capital cost saving"],
  arena:"cl-07"
});

LCEN("s-inventory-2", {
  why:"Safety stock is not \"a bit extra to be safe\". It is **a buffer against demand variability during the lead time** — computable from a formula, and it explains why shortening lead time cuts inventory.",
  outcome:"compute safety stock and the reorder point from service level, demand variability and lead time.",
  scenario:{text:"A pharmacy sells an average of 200 boxes of masks a day, with a daily demand standard deviation of 40 boxes. The supplier delivers in 9 days. The company wants to be in stock in 95% of order cycles.",
            ask:"How many boxes of buffer, and at what stock level do they reorder?"},
  fw:{title:"Safety stock = z × daily demand standard deviation × √lead time",
      rows:[["z","The service-level factor: 95% ≈ 1.65 · 99% ≈ 2.33"],
            ["Daily standard deviation","How much demand swings around the average"],
            ["√lead time","Variability accumulates with the square root of the days"],
            ["Reorder point","Average demand × lead time + safety stock"]],
      warn:"Cutting lead time from 9 days to 4 removes a third of the safety stock — usually cheaper than holding more inventory."},
  ex:{label:"Pharmacy · masks",
      rows:[["Average demand","200 boxes/day"],["Demand standard deviation","40 boxes/day"],["Lead time","9 days"],
            ["Target service level","95%","z ≈ 1.65"]],
      read:"Across the 9-day lead time, average demand is 1,800 boxes. The buffer only has to cover the variation around that."},
  mini:{q:"What does safety stock buffer against?",
        opts:[["A","Demand variability during the lead time","Correct. With no demand variation, or instant delivery, no safety stock is needed."],
              ["B","Average demand during the lead time","That is the main part of the reorder point, not the buffer."],
              ["C","The supplier raising prices","Not what safety stock is for."],
              ["D","Goods spoiling in the warehouse","A separate problem with a separate fix."]],
        correct:"A", kind:"framework"},
  calc:{q:"How much safety stock should be held, in boxes?", unit:"boxes", answer:198, tol:0.5,
        solution:"1.65 × 40 × √9 = 1.65 × 40 × 3 = **198 boxes**. Reorder point = 200 × 9 + 198 = 1,998 boxes.",
        hint:"Multiply z by the daily standard deviation and the square root of the lead time."},
  slide:{headline:"Hold 198 boxes of buffer and reorder at about 2,000 — shortening lead time is the cheapest way to cut the buffer",
         left:"A sawtooth inventory chart with the reorder point and the safety stock band", right:"3 points: 198-box buffer · reorder at 1,998 · 9 days → 4 days removes a third of the buffer",
         rule:"Draw the sawtooth chart — people outside supply chain see immediately where the buffer sits."},
  mistakes:[["Multiplying by lead time instead of its square root","The buffer comes out three times too large."],
            ["Confusing the buffer with lead-time demand","The reorder point contains both."],
            ["One service level for every item","Critical and minor items need different levels."],
            ["Ignoring lead-time variability","An unreliable supplier needs a larger buffer."]],
  checklist:["Choose z from the service level","Compute safety stock","Compute the reorder point",
             "Explain the square root of lead time","Propose shortening lead time to cut the buffer"],
  arena:"cl-07"
});
